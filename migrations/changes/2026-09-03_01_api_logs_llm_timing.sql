-- คำอธิบายคอลัมน์ (ไม่ใช้ COMMENT ON COLUMN ตามกติกาของโปรเจกต์):
--   llm_ms     เวลารวมที่ "งานนี้" นั่งรอ LLM ตอบ · NULL = แถวที่ไม่ใช่งาน webhook
--              (แถว HTTP ปกติจาก config/apiLogger.ts ไม่มีตัวเลขนี้ และไม่ควรมี)
--   llm_calls  จำนวนครั้งที่เรียก LLM ต่อ 1 ข้อความ — ตัวคูณที่มองไม่เห็นมาตลอด
--              ใช้ตอบว่า "ช้าเพราะเรียกหลายครั้ง" หรือ "เรียกครั้งเดียวแต่ครั้งนั้นช้า"
--   own_ms     เวลาที่เป็นงานของเราเอง (DB + LINE API + โค้ด) = processed - llm_ms
--              เก็บเป็นคอลัมน์จริงแทนที่จะให้คนอ่านคำนวณเอง เพราะสูตรต้องหัก queue_waited_ms
--              ออกจาก duration_ms ก่อน ซึ่งเป็นจุดที่คนคำนวณผิดได้ง่ายและผิดแบบเงียบ ๆ
--
--  ⚠️ ทั้งสามค่าเป็น "เท่าที่นับได้ ณ ตอนจบงาน" — งานที่ถูก abort เพราะหมดงบเวลายังรันต่อ
--     เบื้องหลังและบวกเวลา LLM ต่อได้หลังบันทึกไปแล้ว (index.ts เขียนเตือนไว้ตรงจุดเดียวกัน)
ALTER TABLE public.api_logs
  ADD COLUMN IF NOT EXISTS llm_ms    int,
  ADD COLUMN IF NOT EXISTS llm_calls smallint,
  ADD COLUMN IF NOT EXISTS own_ms    int;
